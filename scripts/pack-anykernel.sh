#!/usr/bin/env bash
# Package a raw arm64 Image into an AnyKernel3 flashable zip for nabu.
#
#   usage: pack-anykernel.sh <path-to-Image> [branch] [sha]
#
# AnyKernel3 keeps the device's existing boot header, ramdisk and vendor_boot
# dtb untouched and only swaps the kernel, which is exactly what nabu needs:
# the stock boot.img holds a raw (uncompressed) Image and the DTB lives in
# vendor_boot.
set -euo pipefail

IMAGE="${1:?usage: pack-anykernel.sh <Image> [branch] [sha]}"
BRANCH="${2:-unknown}"
SHA="${3:-unknown}"
OUTDIR="${OUTDIR:-$PWD/out}"
WORK="$PWD/ak3"

[ -f "$IMAGE" ] || { echo "ERROR: $IMAGE not found" >&2; exit 1; }
mkdir -p "$OUTDIR"

rm -rf "$WORK"
git clone --depth 1 https://github.com/osm0sis/AnyKernel3.git "$WORK"
rm -rf "$WORK/.git" "$WORK/.github"

# Only the kernel payload is replaced.
cp "$IMAGE" "$WORK/Image"
rm -f "$WORK"/*.zip "$WORK/placeholder" 2>/dev/null || true

cat > "$WORK/anykernel.sh" <<EOF
### AnyKernel3 Ramdisk Mod Script
## nabu (Xiaomi Pad 5) - generated by nabu-kernel-ci

### AnyKernel setup
# global properties
properties() { '
kernel.string=nabu 4.14.180 (${BRANCH}@${SHA}) KSU+SUSFS
do.devicecheck=1
do.modules=0
do.systemless=1
do.cleanup=1
do.cleanuponabort=0
device.name1=nabu
device.name2=
device.name3=
device.name4=
device.name5=
supported.versions=
supported.patchlevels=
supported.vendorpatchlevels=
'; } # end properties

### AnyKernel install
## boot files attributes
boot_attributes() {
set_perm_recursive 0 0 755 644 \$RAMDISK/*;
set_perm_recursive 0 0 750 750 \$RAMDISK/init* \$RAMDISK/sbin;
} # end attributes

# boot shell variables
BLOCK=/dev/block/bootdevice/by-name/boot;
IS_SLOT_DEVICE=1;
RAMDISK_COMPRESSION=auto;
PATCH_VBMETA_FLAG=auto;

# import functions/variables and setup patching - see for reference (DO NOT REMOVE)
. tools/ak3-core.sh;

# boot install
dump_boot;
write_boot;
## end boot install
EOF

ZIP_NAME="nabu-kernel-${BRANCH}-${SHA}.zip"
( cd "$WORK" && zip -r9 "$OUTDIR/$ZIP_NAME" . -x '*.git*' >/dev/null )

echo "package: $OUTDIR/$ZIP_NAME"
ls -lh "$OUTDIR/$ZIP_NAME"
